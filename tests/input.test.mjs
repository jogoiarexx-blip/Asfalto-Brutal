import assert from 'node:assert/strict';
import {Input} from '../js/input.js';
const listeners=new Map();const on=(type,fn)=>{if(!listeners.has(type))listeners.set(type,[]);listeners.get(type).push(fn)};
globalThis.addEventListener=on;
globalThis.document={addEventListener:on,querySelectorAll:()=>[],hidden:false};
let mockPad=null;Object.defineProperty(globalThis,'navigator',{configurable:true,value:{getGamepads:()=>mockPad?[mockPad]:[]}});
const dispatch=(type,code)=>{for(const fn of listeners.get(type)||[])fn({code,repeat:false,preventDefault(){}})};
const input=new Input();
for(const key of ['accelerating','braking','boosting'])assert.equal(input[key],false,key+' must return boolean false with no gamepad');

dispatch('keydown','KeyD');assert.equal(input.steer,1,'D sends screen RIGHT');dispatch('keyup','KeyD');
dispatch('keydown','KeyA');assert.equal(input.steer,-1,'A sends screen LEFT');dispatch('keyup','KeyA');
dispatch('keydown','ArrowRight');assert.equal(input.steer,1);dispatch('keyup','ArrowRight');
dispatch('keydown','ArrowLeft');assert.equal(input.steer,-1);dispatch('keyup','ArrowLeft');
dispatch('keydown','KeyJ');assert.deepEqual(input.consumeHits(),{left:true,right:false});
dispatch('keydown','KeyK');assert.deepEqual(input.consumeHits(),{left:false,right:true});
dispatch('keydown','Digit4');assert.equal(input.consumeWeapon('chain'),'machete');
dispatch('keydown','Digit5');assert.equal(input.consumeWeapon('chain'),'baton');
dispatch('keydown','KeyQ');assert.equal(input.consumeWeapon('chain'),'baton');
dispatch('keydown','KeyE');assert.equal(input.consumeWeapon('chain'),'club');
dispatch('keydown','KeyH');assert.equal(input.consumeDebug(),true);assert.equal(input.consumeDebug(),false);
dispatch('keydown','KeyP');assert.equal(input.consumePause(),true);
mockPad={axes:[.8],buttons:Array.from({length:17},()=>({pressed:false}))};mockPad.buttons[7].pressed=true;input.update();assert.equal(input.padConnected,true);assert.equal(input.accelerating,true);assert.equal(input.steer,.8);
mockPad.buttons[2].pressed=true;input.update();assert.deepEqual(input.consumeHits(),{left:true,right:false});
input.update();assert.deepEqual(input.consumeHits(),{left:false,right:false},'held button must not repeat attacks');
mockPad.buttons[2].pressed=false;input.update();
mockPad.buttons[5].pressed=true;input.update();assert.deepEqual(input.consumeHits(),{left:false,right:true});
mockPad.buttons[5].pressed=false;input.update();
mockPad.buttons[13].pressed=true;input.update();assert.equal(input.consumeWeapon('chain'),'club','D-pad changes equipped weapon');
mockPad.buttons[13].pressed=false;input.update();
mockPad=null;input.update();assert.equal(input.padConnected,false);dispatch('keydown','KeyD');input.reset();assert.equal(input.steer,0);for(const key of ['accelerating','braking','boosting'])assert.equal(input[key],false);
console.log('Controles de teclado, ataques, debug e gamepad: OK.');
