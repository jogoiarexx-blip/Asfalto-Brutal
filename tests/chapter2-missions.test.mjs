import assert from 'node:assert/strict';
import {MISSIONS,missionById,missionUnlocked,normalizeCampaign,evaluateMission,completeMission} from '../js/jailbreak-campaign.js';
import {initialMissionRun,advanceMissionRun,missionRunStatus,missionTargets} from '../js/mission-events.js';
import {forksFor,roadCenter,activeFork,forkOffset,graphValid} from '../js/road-network.js';
import {CHECKPOINT_DISTANCES} from '../js/checkpoints.js';
assert.equal(MISSIONS.length,9,'three missions added to chapter II');
assert.deepEqual(MISSIONS.slice(0,6).map(m=>m.id),['primeira-marcha','acerto-de-contas','fio-da-navalha','fora-do-radar','correio-urgente','dono-da-pista']);
for(const route of ['coast','desert','highlands']){
 const forks=forksFor(route);
 assert.equal(forks.length,3,'three alternate roads on each map');
 assert.equal(graphValid(route),true);
 for(const fork of forks)assert.ok(!CHECKPOINT_DISTANCES.some(z=>fork.start<=z&&z<=fork.end),'mandatory checkpoints remain on shared road');
}
const previous=normalizeCampaign({version:1,completed:MISSIONS.slice(0,6).map(m=>m.id)});
assert.equal(previous.completed.length,6,'old save remains compatible');
assert.equal(missionUnlocked(previous,MISSIONS[6].id),true,'chapter II unlocks after completing chapter I');
assert.equal(missionUnlocked(previous,MISSIONS[7].id),false);
const courier=missionById('correio-enseada');
assert.equal(courier.route,'coast');
assert.deepEqual(courier.requiredForks,['enseada']);
assert.equal(missionTargets(courier).length,2);
let run=initialMissionRun(courier);
assert.deepEqual(missionRunStatus(courier,run),['DESVIO ENSEADA PENDENTE','ENCOMENDA PENDENTE']);
let p={z:535,x:roadCenter('coast',535,'main'),pathId:'main'};
let result=advanceMissionRun(courier,run,p,534);
assert.equal(result.run.cargoPicked,false,'main road cannot collect side-route cargo');
p={z:535,x:roadCenter('coast',535,'enseada')+9,pathId:'enseada'};
result=advanceMissionRun(courier,run,p,534);
assert.equal(result.run.cargoPicked,false,'cargo requires close lateral approach');
p={z:535,x:roadCenter('coast',535,'enseada'),pathId:'enseada'};
result=advanceMissionRun(courier,run,p,534.5);run=result.run;
assert.equal(run.cargoPicked,true,'package collected on the real side road');
assert.equal(run.visitedForks.enseada,true,'separated branch visit registered');
assert.ok(result.events.some(x=>x.includes('ENCOMENDA')));
assert.equal(run.cargoDelivered,false);
result=advanceMissionRun(courier,run,{z:3300,x:roadCenter('coast',3300,'main'),pathId:'main'},3300.4);
assert.equal(result.run.cargoDelivered,false,'reverse crossing does not deliver');
result=advanceMissionRun(courier,run,{z:3400,x:roadCenter('coast',3400,'main'),pathId:'main'},3399);
assert.equal(result.run.cargoDelivered,false,'missing destination does not count');
result=advanceMissionRun(courier,run,{z:3300,x:roadCenter('coast',3300,'main'),pathId:'main'},3299.5);
run=result.run;
assert.equal(run.cargoDelivered,true,'cargo delivered on main road');
assert.deepEqual(missionRunStatus(courier,run),['DESVIO ENSEADA OK','ENTREGA OK']);
const stats={finished:true,checkpointsValid:true,place:6,health:50,visitedForks:run.visitedForks,cargoDelivered:run.cargoDelivered};
assert.equal(evaluateMission(courier,stats).success,true);
assert.equal(evaluateMission(courier,{...stats,cargoDelivered:false}).success,false,'cannot succeed without handoff');
assert.equal(evaluateMission(courier,{...stats,visitedForks:{}}).success,false,'cannot succeed if fork was skipped');
assert.equal(evaluateMission(courier,{...stats,health:15}).success,false);
const fail=completeMission(previous,courier.id,{...stats,cargoDelivered:false});
assert.equal(fail.bonus,0);assert.equal(fail.campaign.completed.length,6);
const completed=completeMission(previous,courier.id,stats);
assert.equal(completed.bonus,1900);
assert.equal(missionUnlocked(completed.campaign,'sombra-do-canion'),true);
assert.equal(completeMission(completed.campaign,courier.id,stats).bonus,0,'one-time mission bonus');
const pursuit=missionById('sombra-do-canion');
assert.equal(pursuit.policeStart,true);
assert.equal(evaluateMission(pursuit,{finished:true,checkpointsValid:true,escapes:1,visitedForks:{}}).success,false);
assert.equal(evaluateMission(pursuit,{finished:true,checkpointsValid:true,escapes:0,visitedForks:{canion:true}}).success,false);
assert.equal(evaluateMission(pursuit,{finished:true,checkpointsValid:true,escapes:1,visitedForks:{canion:true}}).success,true);
const final=missionById('pacto-das-serras');
assert.equal(evaluateMission(final,{finished:true,checkpointsValid:true,place:4,hits:1,visitedForks:{pedreira:true,colina:true}}).success,true);
assert.equal(evaluateMission(final,{finished:true,checkpointsValid:true,place:4,hits:1,visitedForks:{pedreira:true}}).success,false);
assert.equal(evaluateMission(final,{finished:true,checkpointsValid:true,place:6,hits:1,visitedForks:{pedreira:true,colina:true}}).success,false);
assert.equal(evaluateMission(final,{finished:true,checkpointsValid:true,place:4,hits:0,visitedForks:{pedreira:true,colina:true}}).success,false);
for(const id of ['enseada','canion','pedreira','colina']){
 const route=id==='enseada'?'coast':id==='canion'?'desert':'highlands';
 const fork=forksFor(route).find(f=>f.id===id),z=(fork.start+fork.end)/2;
 assert.equal(activeFork(route,z).id,id);
 assert.ok(Math.abs(forkOffset(fork,z))>12);
}
console.log('Chapter II v2.1.0: nine missions, nine forks, package collection, delivery, chase and rewards OK');
