import assert from 'node:assert/strict';
import {FALL_TIME,RECOVERY_GRACE,POLICE_TRIGGER_TIME,dangerousImpact,nextFall,pursuitTrigger,pursuitStep,updateHeat} from '../js/encounters.js';
import {curveAt} from '../js/config.js';
assert.ok(FALL_TIME>1.5&&RECOVERY_GRACE>=1,'fall and grace timings must be usable');
assert.equal(dangerousImpact(60,21,23),true,'fast collision should throw rider');
assert.equal(dangerousImpact(28,25,25),false,'slow impact should not force fall');
assert.equal(dangerousImpact(60,55,11),false,'minor guardrail scrape must not throw rider');
assert.equal(dangerousImpact(44,7,16),false,'minor overlap should not throw rider');
assert.equal(dangerousImpact(42,9,16),true,'significant bike crash may throw rider');
const f={remaining:FALL_TIME,total:FALL_TIME,side:-1};
assert.equal(nextFall(f,.5).remaining,FALL_TIME-.5);
assert.equal(nextFall(f,100).remaining,0);
assert.equal(f.remaining,FALL_TIME,'pure fall reducer must not mutate original');
assert.equal(nextFall(null,.1),null);
assert.equal(pursuitTrigger({elapsed:5,heat:30}),true,'committing attacks attracts police');
assert.equal(pursuitTrigger({elapsed:10,heat:3}),false);
assert.equal(pursuitTrigger({elapsed:POLICE_TRIGGER_TIME+1,heat:0,playerZ:700}),true,'patrol can appear on long race');
assert.equal(pursuitTrigger({elapsed:POLICE_TRIGGER_TIME+1,heat:0,playerZ:300}),false);
assert.equal(pursuitTrigger({elapsed:60,heat:100,alreadyDeployed:true}),false,'no duplicate police');
assert.equal(pursuitTrigger({elapsed:12,heat:60,nextAllowed:50}),false,'do not bypass cooldown');
assert.equal(updateHeat(90,0,{offense:true}),100,'wanted clamps');
assert.ok(updateHeat(60,2)<60,'wanted cools down');
assert.ok(updateHeat(60,2,{policeNear:true})>updateHeat(60,2),'nearby police slow decay');
const p={x:curveAt(900)+4.5,z:900,speed:55};
const cop={z:850,speed:33,laneOffset:-3};
const moved=pursuitStep(cop,p,.016,curveAt(850),curveAt(p.z),65);
assert.ok(moved.speed>cop.speed&&moved.speed<=63);
assert.ok(moved.laneOffset>cop.laneOffset,'police seeks bike lane');
assert.ok(moved.z>cop.z);
let simulated={...cop};for(let i=0;i<100;i++){const v=pursuitStep(simulated,p,.016,curveAt(simulated.z),curveAt(p.z),65);simulated={...simulated,...v}}
assert.ok(simulated.laneOffset<=5.15&&simulated.laneOffset>=-5.15,'no patrol driving beyond road');
assert.ok(simulated.speed<=63,'police speed must remain bounded and escape remain possible');
