import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {renderWorldAndHero,syncHeroLighting,heroSceneHealth} from '../js/hero-compositor.js';
import {heroDiagnostic} from '../js/debug-hero.js';
const log=[];
const renderer={autoClear:true,clear(...args){log.push(['clear',...args])},clearDepth(){log.push(['clearDepth'])},render(scene){log.push(['render',scene])}};
assert.equal(renderWorldAndHero(renderer,'roadScene','heroScene',{}),true);
assert.deepEqual(log,[['clear',true,true,true],['render','roadScene'],['clearDepth'],['render','heroScene']]);
assert.equal(renderer.autoClear,true,'never leave global renderer state mutated');
log.length=0;renderer.autoClear=false;
assert.equal(renderWorldAndHero(renderer,'road','bike',{}),true);
assert.equal(renderer.autoClear,false,'respect existing rendering preference');
let count=0;
const throws={autoClear:true,clear(){},render(){if(++count===2)throw Error('WebGL context lost')},clearDepth(){}};
assert.throws(()=>renderWorldAndHero(throws,'world','hero',{}),/WebGL context lost/);
assert.equal(throws.autoClear,true,'restore state even on render error');
assert.equal(renderWorldAndHero(renderer,null,'hero',{}),false);
const copyColor=n=>({n,copy(from){this.n=from.n}});
const world={hemi:{intensity:2,color:copyColor(11),groundColor:copyColor(22)},sun:{intensity:5,color:copyColor(33),position:{x:9,y:8,z:7}}};
const hemi={intensity:1,color:copyColor(0),groundColor:copyColor(0)};
const sun={intensity:1,color:copyColor(0),position:{copy(v){Object.assign(this,v)}}};
syncHeroLighting(world,hemi,sun);
assert.equal(hemi.intensity,2);assert.equal(sun.intensity,5);
assert.equal(hemi.groundColor.n,22);assert.equal(sun.color.n,33);
assert.equal(sun.position.x,9);
const scene={},leaf={isMesh:true,visible:true,geometry:{attributes:{position:{count:12}}}};
const hidden={...leaf,visible:false};
const group={visible:true,parent:scene};
const lean={visible:true,traverse(fn){fn({...leaf,parent:lean});fn({...hidden,parent:lean});}};
const vehicle={group,lean};
assert.deepEqual(heroSceneHealth(vehicle,scene),{attached:true,meshes:2,visible:1,invalid:0});
assert.equal(heroSceneHealth(vehicle,{}).attached,false);
const game={playerBike:vehicle,scene,player:{x:0,z:42,speed:19},mode:'race',cameraMode:'chase',heroProbe:{x:0,y:-.2,z:.3},renderer:{shadowMap:{enabled:false},info:{render:{calls:2,triangles:100}},getContext(){throw Error('no GL')}},camera:{position:{x:1,y:3,z:5}}};
assert.equal(heroDiagnostic(game).visibleMeshes,1);
assert.equal(heroDiagnostic(game).video,'WebGL indisponível');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const code=fs.readFileSync(path.join(root,'js/game.js'),'utf8');
assert.match(code,/this\.scene\.add\(this\.playerBike\.group\)/,'player must share world scene with rivals');
assert.match(code,/this\.scene\.add\(this\.heroShadowAnchor\)/,'ground shadow must be in world scene');
assert.match(code,/this\.renderer\.render\(this\.scene,this\.camera\)/,'single scene render path');
assert.match(code,/this\.heroShadowAnchor\.position\.copy\(this\.playerBike\.group\.position\)/,'shadow tracks bike');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(html,/V 2\.1\.0/);
console.log('Render 3D de jogador e rivais em uma única cena: OK.');
