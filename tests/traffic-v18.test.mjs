import assert from 'node:assert/strict';
import {curveAt} from '../js/config.js';
import {moveBike} from '../js/physics.js';
import {rivalStyle,RIVAL_STYLES,rivalPace,rivalLaneRate,rivalAttackCooldown} from '../js/rival-styles.js';
import {planTraffic,trafficLaneOffset} from '../js/traffic-ai.js';
import {separateNpcPair} from '../js/npc-contact.js';
import {evolveTraction} from '../js/traction.js';
import {HULLS,footprintOverlap} from '../js/collision.js';
assert.equal(RIVAL_STYLES.length,6);
assert.equal(new Set(RIVAL_STYLES.map(x=>x.id)).size,6,'six unique personalities');
assert.equal(rivalStyle(6),rivalStyle(0));
assert.ok(rivalPace(rivalStyle(1),42)>rivalPace(rivalStyle(0),42),'sprinter outpaces cautious rival');
assert.ok(rivalAttackCooldown(rivalStyle(2),.6)<rivalAttackCooldown(rivalStyle(0),.6),'aggressive rival strikes more often');
assert.ok(rivalLaneRate(rivalStyle(3))>rivalLaneRate(rivalStyle(4)),'technician changes lane faster');
assert.equal(trafficLaneOffset(-1),-3.95);assert.equal(trafficLaneOffset(1),3.95);
const car=(lane,z,speed=25,cruiseSpeed=30)=>({lane,targetLane:lane,laneOffset:lane*3.95,z,speed,cruiseSpeed,vehicle:{kind:'car'}});
const follower=car(0,100,31),leader=car(0,115,12);
const passing=planTraffic(follower,[follower,leader],.1);
assert.notEqual(passing.targetLane,0,'clear adjacent lane should permit an overtake');
assert.ok(Math.abs(passing.offset)<.21,'lane changes must not teleport car sideways');
const leftBlocked=car(-1,111,18),rightBlocked=car(1,112,17);
const following=planTraffic(follower,[leader,leftBlocked,rightBlocked],.1);
assert.equal(following.targetLane,0,'blocking both lanes prevents unsafe passing');
assert.ok(following.speed<follower.speed,'follower slows down behind slower traffic');
const bikeBehind={laneOffset:-3.95,z:95,speed:55,vehicle:{kind:'bike'}};
const rightBlocked2=car(1,112,18);
assert.notEqual(planTraffic(follower,[leader,bikeBehind,rightBlocked2],.1).targetLane,-1,'do not cut in front of fast bike behind');
const calm=planTraffic(car(0,100,23),[],.1);assert.equal(calm.targetLane,0);
assert.ok(calm.speed>23,'free-flowing traffic accelerates toward cruise speed');
const hot=evolveTraction({lastInputSteer:0,tractionLoss:.35},{speed:60,steer:1,brake:true,dt:.016});
const mild=evolveTraction({lastInputSteer:0,tractionLoss:0},{speed:27,steer:.1,dt:.016});
assert.ok(hot.loss>mild.loss&&hot.grip<mild.grip,'braking hard in a turn loses tyre grip');
let fading=.6;for(let i=0;i<160;i++)fading=evolveTraction({tractionLoss:fading,lastInputSteer:0},{speed:25,steer:0,dt:.016}).loss;
assert.ok(fading<.01,'grip recovers after the slide');
const state={x:curveAt(0),z:0,speed:55,nitro:100,steer:0,lateralVelocity:0,tractionLoss:0};
const turnA={...state},turnB={...state};for(let i=0;i<35;i++){
 moveBike(turnA,{steer:1,brake:true},.016,'coast');
 moveBike(turnB,{steer:.2},.016,'coast');
}
assert.ok(turnA.tractionLoss>turnB.tractionLoss,'real bike dynamics respond differently to skids');
assert.ok(Number.isFinite(turnA.x)&&Number.isFinite(turnA.slideVelocity),'stable simulated drift');
const npc=(kind,lane,z,speed=27)=>({vehicle:{kind},x:curveAt(z)+lane,z,laneOffset:lane,speed,old:{x:curveAt(z)+lane,z,yaw:0}});
const carA=npc('car',0,150,30),carB=npc('car',.2,151,20);
const impact=separateNpcPair(carA,carB);
assert.ok(impact,'car/car collision should register');
assert.ok(!footprintOverlap({...carA,yaw:0,...HULLS.car},{...carB,yaw:0,...HULLS.car}),'car separation prevents embedding');
const moto=npc('bike',.1,200,45),vehicle=npc('car',.2,201,20);
assert.ok(separateNpcPair(moto,vehicle),'bike/car npc contact detected');
assert.ok(!footprintOverlap({...moto,yaw:0,...HULLS.bike},{...vehicle,yaw:0,...HULLS.car}),'bike/car separate');
const distant=npc('bike',-4.7,350,40),carFar=npc('car',4.7,350,20);
assert.equal(separateNpcPair(distant,carFar),null,'separated lanes do not collide');
const crossed=npc('bike',0,490,60),slow=npc('car',0,503,18);crossed.z=507;slow.z=504;
assert.ok(separateNpcPair(crossed,slow),'swept contact catches a bike crossing a car in one frame');
console.log('v1.8: rival personalities, cautious lane changes, real grip loss, bike/car & car/car collision OK.');
