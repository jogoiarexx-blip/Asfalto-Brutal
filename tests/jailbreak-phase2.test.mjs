import assert from 'node:assert/strict';
import {ARREST_TIME,policeArrestStep} from '../js/encounters.js';
import {MISSIONS,evaluateMission,completeMission} from '../js/jailbreak-campaign.js';
import {createCheckpoints,advanceCheckpoints,missedCheckpoint,nextCheckpoint,allCheckpointsPassed} from '../js/checkpoints.js';
const rider={x:0,z:100,speed:0},cop={x:1,z:97,speed:0};
assert.equal(ARREST_TIME>2,true);
let bar=0;for(let i=0;i<180;i++)bar=policeArrestStep(bar,{player:rider,police:cop},1/60);
assert.equal(bar,ARREST_TIME,'policial deve capturar após cerco prolongado');
assert.equal(policeArrestStep(1,{player:rider,police:cop,protectedRider:true},.1)<1,true,'recuperacao protege contra prisao');
assert.equal(policeArrestStep(1,{player:{...rider,speed:30},police:cop},.1)<1,true,'movimento desbloqueia cerco');
assert.equal(policeArrestStep(1,{player:rider,police:{...cop,x:12}},.1)<1,true,'distancia lateral libera cerco');
assert.equal(policeArrestStep(1,{player:rider,police:{...cop,z:60}},.1)<1,true,'distancia longitudinal libera cerco');
assert.equal(policeArrestStep(1,{player:rider,police:{...cop,speed:35}},.1)<1,true,'nao prender durante ultrapassagem em velocidade');
assert.equal(policeArrestStep(1,{player:rider,police:null},.1)<1,true,'policial dispensado zera risco');
assert.equal(policeArrestStep(0,{player:rider,police:cop},-1),0,'dt negativo nao deve preencher barra');
assert.equal(policeArrestStep(999,{player:rider,police:cop},.2),ARREST_TIME,'barra tem limite');
let track=createCheckpoints();
assert.equal(missedCheckpoint(track,949),null);
assert.equal(missedCheckpoint(track,963),950);
assert.equal(missedCheckpoint(track,962),null);
assert.equal(missedCheckpoint(track,NaN),null);
assert.equal(missedCheckpoint(track,1000),950);
track=advanceCheckpoints(track,949.6,950.6,0);
assert.equal(track.passed,1);
assert.equal(missedCheckpoint(track,9500),1900,'nao aceitar pulo de postos');
track=advanceCheckpoints(track,1899,1901,0);
track=advanceCheckpoints(track,2849,2851,0);
assert.equal(allCheckpointsPassed(track),true);
assert.equal(nextCheckpoint(track),null);
assert.equal(missedCheckpoint(track,4000),null,'pista concluida nao tem posto perdido');
const pursuit=MISSIONS.find(m=>m.id==='fora-do-radar');
assert.equal(pursuit.minEscapes,1);
assert.equal(evaluateMission(pursuit,{finished:true,place:1,health:70,escapes:0,checkpointsValid:true}).success,false);
assert.equal(evaluateMission(pursuit,{finished:true,place:7,health:70,escapes:1,checkpointsValid:true}).success,true);
assert.equal(evaluateMission(pursuit,{finished:true,place:7,health:20,escapes:1,checkpointsValid:true}).success,false);
assert.equal(evaluateMission(pursuit,{finished:false,place:1,health:70,escapes:1}).success,false);
const unlocked={completed:MISSIONS.slice(0,3).map(m=>m.id)};
const fail=completeMission(unlocked,pursuit.id,{finished:true,place:1,health:80,escapes:0});
assert.equal(fail.bonus,0);assert.equal(fail.campaign.completed.length,3,'fuga obrigatoria antes de desbloquear');
console.log('Jailbreak 2.0.7: detencao, imunidade, checkpoint e fuga real — verificacoes OK');
