import assert from 'node:assert/strict';
import {MISSIONS,CAMPAIGN_KEY,loadCampaign,saveCampaign,normalizeCampaign,missionUnlocked,evaluateMission,completeMission} from '../js/jailbreak-campaign.js';
import {CHECKPOINT_DISTANCES,createCheckpoints,advanceCheckpoints,allCheckpointsPassed,nextCheckpoint} from '../js/checkpoints.js';
const map=new Map(),store={getItem:key=>map.get(key)??null,setItem:(k,v)=>map.set(k,v)};
assert.equal(MISSIONS.length,9);
assert.equal(loadCampaign(store).completed.length,0);
assert.equal(missionUnlocked(loadCampaign(store),MISSIONS[0].id),true);
assert.equal(missionUnlocked(loadCampaign(store),MISSIONS[1].id),false);
assert.deepEqual(normalizeCampaign({completed:[MISSIONS[2].id]}).completed,[]);
assert.deepEqual(normalizeCampaign({completed:MISSIONS.map(m=>m.id)}).completed,MISSIONS.map(m=>m.id));
assert.equal(evaluateMission(MISSIONS[0],{finished:true,place:3}).success,true);
assert.equal(evaluateMission(MISSIONS[0],{finished:true,place:4}).success,false);
assert.equal(evaluateMission(MISSIONS[1],{finished:true,place:2,hits:0}).success,false);
assert.equal(evaluateMission(MISSIONS[1],{finished:true,place:5,hits:1}).success,true);
assert.equal(evaluateMission(MISSIONS[2],{finished:true,place:4,falls:1}).success,false);
assert.equal(evaluateMission(MISSIONS[2],{finished:true,place:4,falls:0}).success,true);
assert.equal(evaluateMission(MISSIONS[3],{finished:true,place:7,health:20}).success,false);
assert.equal(evaluateMission(MISSIONS[3],{finished:true,place:7,health:40,escapes:1}).success,true);
assert.equal(evaluateMission(MISSIONS[4],{finished:true,place:4,time:135}).success,true);
assert.equal(evaluateMission(MISSIONS[4],{finished:true,place:4,time:135.01}).success,false);
assert.equal(evaluateMission(MISSIONS[5],{finished:true,place:3,hits:2,falls:1}).success,true);
assert.equal(evaluateMission(MISSIONS[5],{finished:true,place:3,hits:2,falls:2}).success,false);
assert.equal(evaluateMission(MISSIONS[0],{finished:false,place:1}).success,false);
assert.equal(evaluateMission(MISSIONS[0],{finished:true,place:1,checkpointsValid:false}).success,false);
let c=loadCampaign(store);
let failed=completeMission(c,MISSIONS[0].id,{finished:false,place:1});
assert.equal(failed.success,false);assert.equal(failed.bonus,0);
let cleared=completeMission(c,MISSIONS[0].id,{finished:true,place:2});
assert.equal(cleared.success,true);assert.equal(cleared.bonus,550);
assert.equal(missionUnlocked(cleared.campaign,MISSIONS[1].id),true);
assert.equal(completeMission(cleared.campaign,MISSIONS[0].id,{finished:true,place:2}).bonus,0,'bonus nao duplica');
assert.equal(completeMission(c,MISSIONS[2].id,{finished:true,place:1,falls:0}).success,false,'missao bloqueada');
assert.equal(saveCampaign(store,cleared.campaign),true);
assert.ok(map.has(CAMPAIGN_KEY));assert.deepEqual(loadCampaign(store).completed,[MISSIONS[0].id]);
map.set(CAMPAIGN_KEY,'{');assert.equal(loadCampaign(store).completed.length,0);
assert.equal(saveCampaign({setItem(){throw Error('quota')}},cleared.campaign),false);
let gates=createCheckpoints();
assert.deepEqual(gates.gates,CHECKPOINT_DISTANCES);
assert.equal(allCheckpointsPassed(gates),false);
assert.equal(nextCheckpoint(gates),950);
gates=advanceCheckpoints(gates,940,955,0);
assert.equal(gates.passed,1);
gates=advanceCheckpoints(gates,1890,1910,7.8);
assert.equal(gates.passed,1,'fora da pista nao valida posto');
gates=advanceCheckpoints(gates,1890,1910,0);
gates=advanceCheckpoints(gates,2840,2870,1.1);
assert.equal(allCheckpointsPassed(gates),true);
assert.equal(nextCheckpoint(gates),null);
assert.equal(advanceCheckpoints(createCheckpoints(),960,1000,0).passed,0,'nao pode pular posto');
assert.equal(advanceCheckpoints(createCheckpoints(),1000,900,0).passed,0,'cruzamento ao contrario nao conta');
console.log('Campanha Jailbreak capitulo I e checkpoints: 30+ verificacoes OK.');
