import assert from 'node:assert/strict';
import {contactResponse} from '../js/contact-response.js';
import {chooseRivalDefense,guardDamage,dodgeOffset} from '../js/defense.js';
import {HULLS,sweptVehicleHit} from '../js/collision.js';
import {moveBike} from '../js/physics.js';
import {curveAt} from '../js/config.js';
import {animateRider} from '../js/rider-animation.js';
const close=(a,b,tol=1e-6)=>Math.abs(a-b)<=tol;
// Contact normals must use the first hit (swept position), not the final tunneled location.
const p0={x:0,z:0,speed:65,lateralVelocity:0,yaw:0,...HULLS.bike};
const p1={...p0,z:12};
const car={x:0,z:6,speed:14,yaw:0,...HULLS.car};
const time=sweptVehicleHit(p0,p1,car,car);
assert.ok(time!==null,'must detect collision at high speed');
const response=contactResponse(p1,car,HULLS.bike,HULLS.car,{contactDz:p0.z+(p1.z-p0.z)*time-car.z});
assert.ok(response.z < car.z,'must not tunnel through a moving car');
assert.ok(response.speed < p1.speed,'front crash must reduce speed');
assert.ok(response.damageFactor>1,'severe hit scale');
assert.equal(p1.z,12,'solver is pure');
const sideContact=contactResponse({x:1.25,z:8,speed:35,lateralVelocity:-5},{x:0,z:8,speed:32},HULLS.bike,HULLS.bike);
assert.ok(sideContact.x>1,'glancing impact leaves player on same side');
assert.ok(sideContact.lateralVelocity>0,'glance pushes away from other bike');
assert.ok(sideContact.speed>20,'glancing impact should preserve momentum');
const following=contactResponse({x:0,z:10,speed:20},{x:0,z:9,speed:40},HULLS.bike,HULLS.bike,{contactDz:2});
assert.ok(following.z>9&&following.speed>=20,'rear-hit preserves forward response');
const baseRival={x:2,z:100,laneOffset:1.5,aggression:.93,fallen:0,stunTimer:0,defenseCD:0,defenseAttackId:0};
const hero={x:0,z:101};
const strike={id:3,side:-1,age:.11};
assert.equal(chooseRivalDefense(baseRival,hero,strike),'dodge');
assert.equal(chooseRivalDefense({...baseRival,aggression:.65},hero,strike),'guard');
assert.equal(chooseRivalDefense({...baseRival,aggression:.25},hero,strike),'none');
assert.equal(chooseRivalDefense(baseRival,hero,{...strike,side:1}),'none','does not predict opposite side');
assert.equal(chooseRivalDefense({...baseRival,defenseAttackId:3},hero,strike),'none','only once per swing');
assert.equal(chooseRivalDefense({...baseRival,defenseCD:1},hero,strike),'none');
assert.equal(chooseRivalDefense({...baseRival,fallen:1},hero,strike),'none');
assert.equal(chooseRivalDefense(baseRival,hero,{...strike,age:.01}),'none','cannot dodge before telegraph');
assert.equal(chooseRivalDefense(baseRival,hero,{...strike,age:.4}),'none','cannot react after finished strike');
assert.equal(chooseRivalDefense({...baseRival,x:6},hero,strike),'none','rivals out of range ignore strike');
assert.equal(dodgeOffset(2.5,2),4.95);assert.equal(dodgeOffset(-2.5,-2),-4.95);
assert.ok(guardDamage(2,true)<guardDamage(2,false));
const drive=(step,frames,steer=1,brake=false)=>{
 const p={x:curveAt(0),z:0,yaw:0,speed:32,nitro:100,steer:0,lateralVelocity:0};
 for(let k=0;k<frames;k++)moveBike(p,{steer,brake,accel:true},step,'coast');return p;
};
const a=drive(.016,60),b=drive(.032,30);
assert.ok(Math.abs(a.x-b.x)<1.4,'steering robust to frame rate');
assert.ok(a.x-curveAt(a.z)<0,'right key remains screen-right');
assert.ok(drive(.016,60,-1).x-curveAt(drive(.016,60,-1).z)>0);
assert.ok(Math.abs(a.bank)<=.38,'bank is bounded');
assert.ok(drive(.016,60,1,true).speed<a.speed,'braking reduces speed');
const arm=()=>({shoulder:{rotation:{x:0,y:0,z:0}},forearmPivot:{rotation:{x:0,y:0,z:0}},weaponPivot:{rotation:{x:0,y:0,z:0}},weaponSets:{chain:{group:{visible:false}}},updateChain(){}});
const node=()=>({rotation:{x:0,y:0,z:0}});
const pilot={armLeft:arm(),armRight:arm(),rider:node(),headRig:node(),kickLeft:node(),kickRight:node(),weaponType:'chain'};
animateRider(pilot,{dt:.04,steer:1,guard:1,time:2,attackAge:Infinity});
assert.ok(pilot.headRig.rotation.y<0,'head anticipates corner');
assert.ok(pilot.armRight.shoulder.rotation.z>.3,'guard raises forearms');
assert.ok(pilot.kickLeft.rotation.z!==pilot.kickRight.rotation.z,'legs brace independently');
console.log('v1.6: collision response, steering, bank, rival guard/dodge and animated rider checks passed.');
