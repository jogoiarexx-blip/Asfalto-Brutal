import assert from 'node:assert/strict';
import {preparePlayerVehicle,ensurePlayerVehicle,playerOutsideView} from '../js/player-visibility.js';

const mesh = (visible=true) => ({isMesh:true,visible,frustumCulled:true});
const body=mesh(),helmet=mesh(),hiddenExhaust=mesh(false),shadow=mesh();
const lean={visible:false,traverse(fn){for(const m of [body,helmet,hiddenExhaust])fn(m)}};
const rider={visible:false};
const vehicle={group:{visible:false},lean,rider,shadow};
assert.equal(preparePlayerVehicle(vehicle),2);
assert.equal(vehicle.group.visible,true);
assert.equal(lean.visible,true);
assert.equal(rider.visible,true);
assert.equal(body.frustumCulled,false);
assert.equal(helmet.frustumCulled,false);
assert.equal(hiddenExhaust.visible,false,'do not accidentally activate hidden visual effects');
assert.equal(shadow.renderOrder,-1);
vehicle.group.visible=false;lean.visible=false;rider.visible=false;
assert.equal(ensurePlayerVehicle(vehicle,false),true);
assert.equal(vehicle.group.visible,true);
assert.equal(lean.visible,true);
assert.equal(rider.visible,true);
vehicle.rider.visible=false;
assert.equal(ensurePlayerVehicle(vehicle,true),false,'do not interrupt crash animation by restoring rider');
assert.equal(vehicle.rider.visible,false);
assert.equal(ensurePlayerVehicle(null,false),false);
assert.equal(preparePlayerVehicle({group:{}}),0);
assert.equal(playerOutsideView({x:0,y:-.20,z:.5}),false);
assert.equal(playerOutsideView({x:0,y:-.79,z:.5}),true);
assert.equal(playerOutsideView({x:1.02,y:0,z:.5}),true);
assert.equal(playerOutsideView({x:0,y:0,z:-5}),true);
assert.equal(playerOutsideView({x:NaN,y:0,z:0}),true);
console.log('Modelo do jogador, recuperação após quedas e enquadramento: OK.');
