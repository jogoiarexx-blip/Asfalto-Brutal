import assert from 'node:assert/strict';
import {chooseOvertake,resolveRivalPair,policeCurveTarget,skidIntensity} from '../js/race-dynamics.js';
import {curveAt,headingAt} from '../js/config.js';
import {HULLS,footprintOverlap} from '../js/collision.js';
const bike=(lane,z,speed=35,route='coast')=>({x:curveAt(z,route)+lane,z,laneOffset:lane,speed,old:{x:curveAt(z,route)+lane,z,yaw:headingAt(z,route)}});
const rover=bike(0,100,50),lead=bike(0,116,23);
const pass=chooseOvertake(rover,[rover,lead]);
assert.ok(pass!==null,'overtake must choose a lane for slower traffic');
assert.ok(Math.abs(pass)>2,'chosen pass must be outside leader hitbox');
assert.equal(chooseOvertake(rover,[rover,bike(0,119,60)]),null,'do not overtake faster traffic');
assert.equal(chooseOvertake({...rover,fallen:1},[lead]),null,'fallen rider cannot pass');
assert.equal(chooseOvertake(rover,[rover,bike(0,115,20),bike(-2.7,111,30),bike(2.7,113,28)]),null,'no opening means no forced overtake');
const contactA=bike(0,100,45),contactB=bike(.3,101,26);
const result=resolveRivalPair(contactA,contactB);
assert.ok(result&&result.intensity>0,'bikes collide');
assert.ok(!footprintOverlap({...contactA,yaw:0,...HULLS.bike},{...contactB,yaw:0,...HULLS.bike}),'bike pairs separate');
assert.ok(contactA.speed<=45&&contactB.speed<=26,'contact never creates free speed');
const sideA=bike(-.50,130,30),sideB=bike(.55,130,30);
const sideResult=resolveRivalPair(sideA,sideB);
assert.equal(sideResult.side,true);
assert.ok(Math.abs(sideA.x-sideB.x)>=1.18,'side contact creates a lateral gap');
const absentA=bike(-4,10),absentB=bike(4,10);
assert.equal(resolveRivalPair(absentA,absentB),null,'different lanes do not collide');
const down=bike(0,10);down.fallen=1;assert.equal(resolveRivalPair(down,bike(0,10)),null);
// A high-speed crossing whose start and end positions are both widely separated.
const throughA=bike(0,90,70),throughB=bike(0,105,20);
throughA.z=108;throughA.x=curveAt(108);
throughB.z=107;throughB.x=curveAt(107);
const sweep=resolveRivalPair(throughA,throughB);
assert.ok(sweep,'continuous check catches tunnelling even for separated endpoints');
assert.ok(throughA.z<throughB.z,'trailing bike cannot teleport through leader');
assert.ok(!footprintOverlap({...throughA,yaw:0,...HULLS.bike},{...throughB,yaw:0,...HULLS.bike}),'tunnel correction creates a gap');
const cop={z:600,speed:52,laneOffset:1.7},player={z:630,x:curveAt(630,'highlands')+2,speed:50};
const curve=policeCurveTarget(cop,player,'highlands');
assert.ok(curve.curveLimit<=64&&curve.curveLimit>=47,'police has bounded corner speed');
assert.ok(curve.desiredOffset<=5.05&&curve.desiredOffset>=-5.05,'police stays inside rails');
assert.ok(curve.severity>=0&&curve.severity<=1);
assert.ok(skidIntensity({speed:50,steer:1,brake:true})>skidIntensity({speed:50,steer:.1}),'braking turn increases skid');
assert.equal(skidIntensity({speed:4,steer:1,brake:true}),0,'no tyre mark while parked');
assert.ok(skidIntensity({speed:50,steer:1,brake:true,slip:10})<=1,'bounded skid effect');
console.log('v1.7: passing, bike/bike collision SAT, no tunnelling, police bends, tyre skids OK.');
