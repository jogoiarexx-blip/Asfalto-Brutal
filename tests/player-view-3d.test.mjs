import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {bikeViewCoordinates} from '../js/player-view-math.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const zero=bikeViewCoordinates({ndcX:0,ndcY:0,distance:11.2});
assert.equal(zero.x,0);assert.equal(zero.y,0);assert.equal(zero.depth,11.2);
const screenshot=bikeViewCoordinates({ndcX:.02,ndcY:-.14,distance:11.2,fov:75,aspect:1.9});
assert.ok(screenshot.x>0&&screenshot.y<0&&screenshot.depth<16);
assert.deepEqual(bikeViewCoordinates({ndcX:Infinity,ndcY:NaN,distance:NaN}),{depth:12,xNdc:0,yNdc:0,x:0,y:0});
const src=fs.readFileSync(path.join(root,'js/game.js'),'utf8');
const view=fs.readFileSync(path.join(root,'js/player-view-3d.js'),'utf8');
assert.match(src,/playerView3D\.draw\(/);
assert.match(view,/renderer\.render\(scene,camera\)/);
assert.match(view,/finally\s*\{/);
assert.match(view,/body\.quaternion\.copy\(this\.savedRotation\)/);
assert.doesNotMatch(src,/HeroSafeOverlay|HeroPixelProbe|forceSafeOverlay/);
assert.ok(!fs.existsSync(path.join(root,'js/hero-safe-overlay.js')));
assert.ok(!fs.existsSync(path.join(root,'js/hero-pixel-probe.js')));
console.log('Renderização 3D real e restauração de pose: OK');
